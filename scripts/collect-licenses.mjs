import { execFileSync } from "node:child_process";
import { readFile, readdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { createHash } from "node:crypto";

export async function collectNotices(entries, overrides, noticeRoot) {
  let output = "MilkO production dependency notices\nGenerated by pnpm license:collect. Includes the production dependency tree, including packages not retained by bundling.\n";
  const missing = [];
  for (const entry of entries) {
    output += `\n${"=".repeat(72)}\n${entry.name} ${entry.versions.join(", ")} — ${entry.license}\n`;
    const pathsByVersion = new Map();
    for (const path of entry.paths) {
      const manifest = JSON.parse(await readFile(join(path, "package.json"), "utf8"));
      const paths = pathsByVersion.get(manifest.version) ?? [];
      paths.push(path);
      pathsByVersion.set(manifest.version, paths);
    }
    const notices = new Map();
    function record(content, version, file, source) {
      let notice = notices.get(content);
      if (!notice) { notice = { versions: new Set(), files: new Set(), sources: new Set() }; notices.set(content, notice); }
      notice.versions.add(version); notice.files.add(file);
      if (source) notice.sources.add(source);
    }
    for (const version of [...new Set(entry.versions)].sort()) {
      let found = false;
      for (const path of pathsByVersion.get(version) ?? []) {
        const files = (await readdir(path)).filter((name) => /^(?:licen[sc]e|copying|notice)(?:\.|$)/i.test(name)).sort();
        for (const file of files) {
          const content = await readFile(join(path, file), "utf8").catch(() => null);
          if (content) { record(content, version, file); found = true; }
        }
      }
      if (!found) {
        const key = `${entry.name}@${version}`;
        const override = overrides[key];
        if (!override) {
          missing.push(key);
          output += `\nMISSING NOTICE: ${key} requires review.\n`;
          continue;
        }
        const content = await readFile(join(noticeRoot, override.file));
        if (createHash("sha256").update(content).digest("hex") !== override.sha256) {
          throw new Error(`Upstream notice checksum mismatch: ${key}`);
        }
        record(content.toString("utf8"), version, "Upstream notice", override.source);
      }
    }
    for (const [content, notice] of notices) {
      output += `\nVersions: ${[...notice.versions].join(", ")}\n${[...notice.files].sort().join(", ")}\n`;
      for (const source of [...notice.sources].sort()) output += `Source: ${source}\n`;
      output += `${content}\n`;
    }
  }
  return { output, missing };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const packages = JSON.parse(execFileSync("pnpm", ["licenses", "list", "--prod", "--json"], { encoding: "utf8" }));
  const entries = Object.values(packages).flat().sort((a, b) => a.name.localeCompare(b.name));
  const noticeRoot = fileURLToPath(new URL("../licenses/", import.meta.url));
  const overrides = JSON.parse(await readFile(join(noticeRoot, "overrides.json"), "utf8"));
  const { output, missing } = await collectNotices(entries, overrides, noticeRoot);
  await writeFile(join(noticeRoot, "dependencies.txt"), output);
  if (missing.length) {
    console.error(`Missing dependency notices require review:\n${missing.join("\n")}`);
    process.exitCode = 1;
  } else console.log(`Collected notices for ${entries.length} production packages; no missing notices.`);
}
